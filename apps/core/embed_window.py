"""Карточка во всплывающем окне документа (?embed=1).

Окно получает от документа метку modal=<метка> и возвращает её в сообщении
«сохранено». Так документ отличает ответ актуального окна от чужого или
прошлого (static/js/entity-modal.js). Метка — не секрет, а номер открытия окна.
"""
import re

_TOKEN = re.compile(r"^[A-Za-z0-9_-]{1,64}$")


def modal_token(request):
    """Метка окна из адреса; постороннее значение не передаётся дальше."""
    token = request.GET.get("modal", "")
    return token if _TOKEN.match(token) else ""
