"""Понятный отказ в удалении объекта, на который ссылаются другие записи.

Внешние ключи с запретом удаления (PROTECT) не дают удалить документ, на
который ссылаются задачи или другие документы: Django отклоняет удаление
ProtectedError ещё до записи, транзакция откатывается целиком. Здесь — текст
для пользователя. Заголовки задач в нём не раскрываются: удаляющий может не
иметь к ним доступа.
"""


def protected_reason(exc, refused="Документ не удалён"):
    return f"{refused} — {protected_details(exc)}"


def protected_details(exc):
    """Причина отказа без начала фразы: «есть связанные задачи (2). …»"""
    objects = list(getattr(exc, "protected_objects", ()) or ())
    tasks = sum(1 for obj in objects if obj._meta.label == "tasks.Task")
    reasons = []
    if tasks:
        reasons.append(f"есть связанные задачи ({tasks})")
    if len(objects) > tasks or not objects:
        reasons.append("есть ссылки из других документов")
    text = f"{', '.join(reasons)}."
    if tasks:
        text += (" Задачи хранят историю работы, поэтому объект, с которым они связаны, удалить нельзя — "
                 "даже если задачи завершены или отменены.")
    return text


def concurrent_reason(refused="Документ не удалён"):
    """Связь появилась одновременно с удалением: база отклонила удаление при записи."""
    return (f"{refused} — пока шло удаление, появилась ссылка из другой записи (например, "
            "поставили задачу). Обновите страницу.")
